"""Validate the local application ledger and derive readable views. No external writes."""
import argparse
import json
from datetime import datetime, timezone
from pathlib import Path
from html import escape

MARKER = "<!-- generated by job-prep-kit tracker; edit data.json -->"
STATES = {"candidate", "ready", "draft", "submitted", "assessment", "interview", "waiting", "offer", "rejected", "withdrawn", "signed"}
SOURCE_KINDS = {"employer", "school", "personal_notice", "community", "other"}
FOCUS_MODES = {"active": "求职进行中", "closing": "办理收尾", "paused": "已暂停", "complete": "已结束"}


def timestamp(value):
    if not isinstance(value, str):
        raise ValueError("时间必须是带时区的字符串")
    parsed = datetime.fromisoformat(value)
    if parsed.tzinfo is None:
        raise ValueError("时间必须带时区，例如 2030-09-21T18:00:00+08:00")
    return parsed


def fields(value, path, names=()):
    if not isinstance(value, dict):
        raise ValueError(f"{path} 必须是对象")
    for name in names:
        if not isinstance(value.get(name), str) or not value[name].strip():
            raise ValueError(f"{path}.{name} 必须是非空字符串")


def validate(data):
    fields(data, "台账")
    if data.get("schema_version") != 1 or not isinstance(data.get("applications"), list):
        raise ValueError("需要 schema_version=1 和 applications 数组")
    if "scope_note" in data:
        fields(data, "台账", ("scope_note",))
    focus = data.get("focus", {})
    if "focus" in data:
        fields(focus, "focus", ("mode",))
        if focus["mode"] not in FOCUS_MODES:
            raise ValueError("focus.mode 必须是 active/closing/paused/complete")
        if "note" in focus and not isinstance(focus["note"], str):
            raise ValueError("focus.note 必须是字符串")
        if "application_ids" in focus:
            selected = focus["application_ids"]
            if not isinstance(selected, list) or any(not isinstance(item, str) or not item.strip() for item in selected):
                raise ValueError("focus.application_ids 必须是岗位 ID 数组")
        if focus["mode"] == "closing" and not focus.get("application_ids"):
            raise ValueError("focus.application_ids：closing 模式需要明确指定收尾岗位")
    if "workspace_links" in data:
        links = data["workspace_links"]
        fields(links, "workspace_links")
        for label, value in links.items():
            if not isinstance(label, str) or not label.strip() or not isinstance(value, str) or not value.strip():
                raise ValueError("workspace_links 必须是非空标签到非空字符串的映射")
    ids = set()
    for index, app in enumerate(data["applications"]):
        path = f"applications[{index}]"
        fields(app, path, ("id", "company", "project", "role", "status"))
        if "next_action" in app and not isinstance(app["next_action"], str):
            raise ValueError(f"{path}.next_action 必须是字符串")
        if "needs_user" in app and not isinstance(app["needs_user"], str):
            raise ValueError(f"{path}.needs_user 必须是字符串")
        if "location" in app and not isinstance(app["location"], str):
            raise ValueError(f"{path}.location 必须是字符串")
        if "brief" in app:
            fields(app["brief"], f"{path}.brief")
            for key, value in app["brief"].items():
                if not isinstance(value, str):
                    raise ValueError(f"{path}.brief.{key} 必须是字符串")
        if "materials" in app:
            fields(app["materials"], f"{path}.materials", app["materials"].keys() if isinstance(app["materials"], dict) else ())
        for key in ("sources", "events"):
            if key not in app:
                raise ValueError(f"缺少字段 {key}")
        if app["id"] in ids:
            raise ValueError("岗位记录 id 为空或重复")
        ids.add(app["id"])
        if app["status"] not in STATES:
            raise ValueError(f"{app['id']}: 未知状态")
        sources = app["sources"]
        if not isinstance(sources, dict):
            raise ValueError("sources 必须是以来源 id 为键的对象")
        for source_id, source in sources.items():
            fields(source, f"{path}.sources.{source_id}", ("kind", "locator", "checked_at", "excerpt"))
            if source["kind"] not in SOURCE_KINDS:
                raise ValueError("来源需要 kind/locator/checked_at/excerpt")
            timestamp(source["checked_at"])
        submission = app.get("submission")
        if submission is not None:
            fields(submission, f"{path}.submission", ("at", "source"))
            version = submission.get("resume_version")
            missing = submission.get("resume_unavailable_reason")
            if bool(version) == bool(missing):
                raise ValueError(f"{path}.submission: 填 resume_version，或以 resume_unavailable_reason 明确说明历史附件缺失；不能同时填")
            fields(submission, f"{path}.submission", ("resume_version",) if version else ("resume_unavailable_reason",))
            timestamp(submission["at"])
            if sources.get(submission["source"], {}).get("kind") not in {"employer", "personal_notice"}:
                raise ValueError("提交凭证必须指向官网记录或本人发送/收到的凭证")
        stage_evidence = app.get("stage_evidence")
        if "stage_evidence" in app:
            fields(stage_evidence, f"{path}.stage_evidence", ("source", "submission_unavailable_reason"))
            if set(stage_evidence) != {"source", "submission_unavailable_reason"}:
                raise ValueError(f"{path}.stage_evidence 仅允许 source 和 submission_unavailable_reason")
            if sources.get(stage_evidence["source"], {}).get("kind") not in {"employer", "personal_notice"}:
                raise ValueError(f"{path}.stage_evidence.source 必须关联企业官方或本人正式通知")
        if app["status"] == "submitted" and not submission:
            raise ValueError("submitted 必须有提交记录，阶段凭证不能替代")
        if app["status"] in {"assessment", "interview", "waiting", "offer", "signed"} and not submission and not stage_evidence:
            raise ValueError("流程中岗位必须有提交记录或 stage_evidence 正式阶段凭证及提交历史缺口")
        if "result" in app:
            fields(app["result"], f"{path}.result", ("source",))
        if app["status"] in {"offer", "signed", "rejected"}:
            result = app.get("result", {})
            if sources.get(result.get("source"), {}).get("kind") not in {"employer", "personal_notice"}:
                raise ValueError("录用、签约或淘汰必须有 result.source 关联正式结果；个人感觉不是结果")
        if not isinstance(app["events"], list) or not isinstance(app.get("choices", []), list):
            raise ValueError("events/choices 必须是数组")
        if any(not isinstance(choice, str) for choice in app.get("choices", [])):
            raise ValueError(f"{path}.choices 的每项必须是字符串")
        for event_index, event in enumerate(app["events"]):
            fields(event, f"{path}.events[{event_index}]", ("title", "at", "kind"))
            if "note" in event and not isinstance(event["note"], str):
                raise ValueError(f"{path}.events[{event_index}].note 必须是字符串")
            if event.get("time_precision", "exact") not in ("exact", "estimated"):
                raise ValueError(f"{path}.events[{event_index}].time_precision 必须是 exact 或 estimated")
            if event.get("category", "recruitment") not in ("recruitment", "closing"):
                raise ValueError(f"{path}.events[{event_index}].category 必须是 recruitment 或 closing")
            if "done_source" in event:
                fields(event, f"{path}.events[{event_index}]", ("done_source",))
                if event.get("done") is not True or event["done_source"] not in sources:
                    raise ValueError(f"{path}.events[{event_index}].done_source 需要 done=true 并关联现有完成凭证")
            if "source" in event and not isinstance(event["source"], str):
                raise ValueError(f"{path}.events[{event_index}].source 必须是字符串")
            if "done" in event and not isinstance(event["done"], bool):
                raise ValueError("done 必须是 true/false，不能用字符串代替")
            if event["kind"] not in {"deadline", "scheduled", "suggested"}:
                raise ValueError("节点需要 title/at/kind；kind=deadline/scheduled/suggested")
            timestamp(event["at"])
            if event.get("notified_at"):
                timestamp(event["notified_at"])
            if event["kind"] != "suggested" and sources.get(event.get("source"), {}).get("kind") not in {"employer", "school", "personal_notice"}:
                raise ValueError("官方截止/安排必须关联企业、学校或个人通知来源")
    if set(focus.get("application_ids", [])) - ids:
        raise ValueError("focus.application_ids 引用了不存在的岗位 ID")
    return data


def validate_workspace(workspace, data):
    validate(data)
    warnings = []
    for app in data["applications"]:
        submission = app.get("submission")
        if submission and submission.get("resume_unavailable_reason"):
            warnings.append(f"{app['id']}: 历史附件待补：{submission['resume_unavailable_reason']}")
    return warnings


def cell(value):
    return str(value or "—").replace("|", "\\|").replace("\r", " ").replace("\n", " ").replace("<", "&lt;").replace(">", "&gt;")


def follows(app, focus=None):
    """Current user intent is separate from the employer's last known status."""
    focus = focus or {}
    mode = focus.get("mode", "active")
    if mode in {"paused", "complete"} or app["status"] in {"rejected", "withdrawn"}:
        return False
    if "application_ids" in focus and app["id"] not in focus["application_ids"]:
        return False
    return app["status"] != "signed" or mode == "closing"


def pending_events(app, focus=None):
    return sorted((event for event in app["events"] if not event.get("done")
                   and ((focus or {}).get("mode") != "closing" or event.get("category") == "closing")),
                  key=lambda event: timestamp(event["at"]))


def event_age(event, now):
    when = timestamp(event["at"])
    return (when.date() - now.astimezone(when.tzinfo).date()).days


def current_events(app, now, focus=None):
    # Older unresolved events stay in history; passing time is not completion.
    return [event for event in pending_events(app, focus) if -7 <= event_age(event, now) <= 7]


def render(data, now=None):
    validate(data)
    now = now or datetime.now(timezone.utc)
    apps = data["applications"]
    focus = data.get("focus", {})
    submitted = [a for a in apps if a.get("submission")]
    companies = len({(a["company"], a["project"]) for a in submitted})
    wishes = sum(len(a.get("choices", [])) for a in submitted)
    head = [MARKER, "", f"> 生成时间：{now.isoformat(timespec='seconds')}；统计按 company + project 去重。", ""]
    if "scope_note" in data:
        head += ["## 数据范围", "", "<pre>" + escape(data["scope_note"]) + "</pre>", ""]
    if focus:
        head += [f"> 当前安排：{FOCUS_MODES[focus['mode']]}。{cell(focus.get('note', ''))}", ""]
    notified = sum(bool(a.get("stage_evidence")) and not a.get("submission") for a in apps)
    table = head + ["# 投递总表", "", f"仅统计有提交凭证的记录：已投企业/统一项目 {companies}；已投记录 {len(submitted)}；明确登记的志愿 {wishes}（未填不推断）。另有 {notified} 条通知确认阶段（无提交记录，不计入已投）。", "", "| ID | 企业/项目 | 岗位 | 状态 | 下一动作 | 阶段凭证与提交缺口 |", "|---|---|---|---|---|---|"]
    timeline = head + ["# 时间轴", "", "| 时间 | 岗位ID | 节点 | 类型 | 完成 | 来源 |", "|---|---|---|---|---|---|"]
    today = head + ["# 投递日程", "", "仅列当前跟进范围内的事项。建议时间不是官方截止；时间已过仅提示核实，不推断结果。", "", "## 近七天待核实、今天与未来七天", ""]
    next_actions = []
    stage_notes = []
    gaps = []
    older = []
    for app in apps:
        current = follows(app, focus)
        evidence = app.get("stage_evidence")
        stage_note = ""
        if evidence:
            source = app["sources"][evidence["source"]]
            stage_note = f"阶段凭证：{source['locator']}；{source['excerpt']}；提交历史缺口：{evidence['submission_unavailable_reason']}"
            if not app.get("submission"):
                stage_note += "；原始申请时间及岗位关联未知，不计入已投"
            gaps.append(f"- {cell(app['id'])} {cell(stage_note)}")
            stage_notes.append(f"- {cell(app['id'])} · {cell(app['status'])} · {cell(stage_note)}")
        action = app.get("next_action") if current else "当前不跟进；历史动作：" + app.get("next_action", "未记录")
        table.append("| " + " | ".join(cell(x) for x in (app["id"], app["company"] + "/" + app["project"], app["role"], app["status"], action, stage_note)) + " |")
        if (app.get("submission") or {}).get("resume_unavailable_reason"):
            gaps.append(f"- 附件待补：{cell(app['id'])} {cell(app['submission']['resume_unavailable_reason'])}")
        pending = pending_events(app, focus)
        # Do not recycle a stale or distant event's preparation as an undated task.
        if current and app.get("next_action") and (not pending or current_events(app, now, focus)):
            next_actions.append(f"- {cell(app['id'])}：{cell(app['next_action'])}")
        if current and app.get("needs_user"):
            next_actions.append(f"- 待本人处理：{cell(app['id'])} {cell(app['needs_user'])}")
        if current:
            older += [f"- {cell(app['id'])} {cell(e['title'])}（{e['at']}；未标记完成，保留待核实）" for e in pending if event_age(e, now) < -7]
    events = sorted(((timestamp(e["at"]), a, e) for a in apps for e in a["events"]), key=lambda item: item[0])
    for when, app, event in events:
        source = app["sources"].get(event.get("source"), {})
        description = event["title"] + ("；" + event["note"] if event.get("note") else "")
        displayed_time = ("约 " if event.get("time_precision") == "estimated" else "") + event["at"]
        kind = "推算时间，待核实" if event.get("time_precision") == "estimated" else event["kind"]
        provenance = source.get("locator", "助手建议")
        if event.get("done_source"):
            provenance += "；完成依据：" + app["sources"][event["done_source"]]["locator"]
        timeline.append("| " + " | ".join(cell(x) for x in (displayed_time, app["id"], description, kind, "已完成" if event.get("done") else "未标记完成", provenance)) + " |")
        local_now = now.astimezone(when.tzinfo)
        if follows(app, focus) and event in current_events(app, now, focus):
            label = "时间已过，核实状态" if when < now else ("今天" if when.date() == local_now.date() else "未来七天")
            today.append(f"- {label}：{cell(app['id'])} {cell(description)}（{displayed_time}，{kind}）")
    if stage_notes:
        timeline.extend(["", "## 阶段凭证与提交缺口", ""] + stage_notes)
    today.extend(["", "## 下一动作", ""] + (next_actions or ["暂无待办。收到新通知后更新台账。"]))
    if older:
        today.extend(["", "<details><summary>较早的未确认事项（不列入近期待办）</summary>", ""] + older + ["", "</details>"])
    if gaps:
        today.extend(["", "## 历史凭证与资料缺口", "", "资料说明，不自动转成当前任务。", ""] + gaps)
    return {"投递总表.md": table, "时间轴.md": timeline, "投递日程.md": today}


def write_views(workspace, views):
    folder = Path(workspace) / "applications"
    for name in views:
        target = folder / name
        if target.exists() and not target.read_text(encoding="utf-8").startswith(MARKER):
            raise ValueError(f"拒绝覆盖手写文件 {name}；新工作区用 render --output-dir 指向新目录，核对后自行迁移。")
    folder.mkdir(parents=True, exist_ok=True)
    for name, lines in views.items():
        target = folder / name
        temporary = target.with_suffix(".md.tmp")
        temporary.write_text("\n".join(lines) + "\n", encoding="utf-8")
        temporary.replace(target)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["validate", "render"])
    parser.add_argument("--workspace", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, help="可选的视图工作区根目录；输出至其 applications 子目录")
    args = parser.parse_args()
    try:
        data = json.loads((args.workspace / "applications/data.json").read_text(encoding="utf-8"))
        for warning in validate_workspace(args.workspace, data):
            print("提醒：" + warning)
        if args.command == "render":
            from dashboard import write_dashboard
            write_views(args.output_dir or args.workspace, render(data))
            print("本地看板：" + str(write_dashboard(args.workspace, data, args.output_dir)))
        print("校验通过" if args.command == "validate" else "已生成三份视图和看板；以 data.json 为准")
    except (ValueError, OSError, KeyError, TypeError) as exc:
        parser.exit(1, str(exc) + "\n")
